CREATE TABLE IF NOT EXISTS task_compute_job (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 job_key VARCHAR(160) NOT NULL,
 task_id INT NOT NULL,
 dataset_id BIGINT NOT NULL,
 execution_mode VARCHAR(24) NOT NULL,
 plan_id BIGINT NULL,
 assignment_id BIGINT NULL,
 runtime_image_id BIGINT NULL,
 overrides_json TEXT NULL,
 replica_id BIGINT NULL,
 target_node VARCHAR(255) NULL,
 cluster_id VARCHAR(255) NULL,
 comparison_node VARCHAR(255) NULL,
 cpu DOUBLE NULL,
 memory_gi DOUBLE NULL,
 gpu DOUBLE NULL,
 ephemeral_storage_gi DOUBLE NULL,
 state VARCHAR(24) NOT NULL,
 waiting_reason TEXT NULL,
 job_name VARCHAR(63) NULL,
 job_uid VARCHAR(128) NULL,
 migration_id BIGINT NULL,
 attempt INT NOT NULL DEFAULT 0,
 external_prepared TINYINT NOT NULL DEFAULT 0,
 result_json MEDIUMTEXT NULL,
 queued_at DATETIME(3) NOT NULL,
 submitted_at DATETIME(3) NULL,
 bound_at DATETIME(3) NULL,
 next_attempt_at DATETIME(3) NULL,
 finished_at DATETIME(3) NULL,
 cleaned_at DATETIME(3) NULL,
 credential_refreshed_at DATETIME(3) NULL,
 UNIQUE KEY uk_compute_job_key(job_key),
 KEY idx_compute_job_active(state,queued_at),
 KEY idx_compute_job_task(task_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
